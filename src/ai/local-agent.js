const HOOKS = [
  (t) => `✨ ${t}؛ چیزی که خیلی‌ها دنبالش هستن ولی نمی‌دونن از کجا شروع کنن!`,
  (t) => `🤔 تا حالا درباره «${t}» فکر کردی؟ بذار خیلی ساده توضیح بدم...`,
  (t) => `🔥 سه چیزی که قبل از انتخاب «${t}» حتماً باید بدونی!`,
  (t) => `💡 اگه «${t}» برات مهمه، این پست رو ذخیره کن، بعداً لازمت میشه.`,
  (t) => `🛍️ جدیدترین محصولمون رسید: ${t} ❤️`,
];

const CTAS = [
  'برای مشاوره رایگان کافیست همینجا دایرکت بدید 💬',
  'سؤالی داری؟ کامنت بذار، تک‌تک جواب می‌دم 👇',
  'این پست رو برای کسی که بهش نیاز داره بفرست 📩',
  'برای سفارش، دایرکت یا لینک توی بیو 🔗',
  'کد تخفیف ۲۰٪ فقط برای ۴۸ ساعت آینده — از دستش نده ⏰',
];

export function makeCaption({ topic, tone = 'دوستانه', keywords = '' }) {
  const t = topic || 'محصول جدید';
  const kw = keywords ? keywords.split(/[،,]/).map((s) => s.trim()).filter(Boolean) : [];
  const body = [
    pick(HOOKS)(t),
    '',
    `در این پست سراغ ${t} رفتیم و نکته‌های کاربردی‌ای که یه انتخاب درست می‌سازه رو براتون جمع کردیم.`,
    kw.length ? `کلمات کلیدی: ${kw.join('، ')} — همه‌چیز با جزئیات بررسی شده.` : 'همه‌چیز با جزئیات و بر اساس تجربه واقعی بررسی شده.',
    '',
    'رضایت شما، مهم‌ترین سرمایه ماست و کیفیت، خط قرمز ماست. ✅',
    '',
    pick(CTAS),
  ].join('\n');
  const tags = makeHashtags({ topic: t }).groups.flatMap((g) => g.tags).slice(0, 12);
  return { caption: body, hashtags: tags, tone };
}

// ─── ایده محتوا ───────────────────────────────────────────────
const IDEA_BANK = [
  (n) => ({ title: `۳ اشتباه رایج در انتخاب ${n}`, type: 'ریلز', hook: 'شروع با یک اشتباه که اکثر مردم مرتکب می‌شن' }),
  (n) => ({ title: `پشت صحنه آماده‌سازی ${n}`, type: 'استوری', hook: 'نمایش لحظه‌های واقعی و صمیمی کسب‌وکار' }),
  (n) => ({ title: `راهنمای کامل خرید ${n}`, type: 'پست', hook: 'پست ذخیره‌ای با چک‌لیست کاربردی' }),
  (n) => ({ title: `نظر مشتری‌ها درباره ${n}`, type: 'ریلز', hook: 'تجمیع ویدیوهای رضایت مشتریان' }),
  (n) => ({ title: `مقایسه دو گزینه محبوب ${n}`, type: 'پست', hook: 'جدول مقایسه و نتیجه شفاف' }),
  (n) => ({ title: `یک روز کاری ما در حوزه ${n}`, type: 'ریلز', hook: 'ولاگ کوتاه با ریتم سریع' }),
  (n) => ({ title: `پاسخ به ۵ سؤال پرتکرار درباره ${n}`, type: 'استوری', hook: 'استیکر سؤال و پاسخ تعاملی' }),
  (n) => ({ title: `تخفیف ویژه محدود روی ${n}`, type: 'استوری', hook: 'شمارش معکوس و استیکر لینک' }),
];

export function makeIdeas({ niche, count = 6 }) {
  const n = niche || 'کسب‌وکار شما';
  const n2 = Math.min(Number(count) || 6, IDEA_BANK.length);
  return { ideas: take(IDEA_BANK, n2).map((fn) => fn(n)) };
}

// ─── هشتگ ─────────────────────────────────────────────────────
export function makeHashtags({ topic }) {
  const t = String(topic || 'محصول').trim();
  const core = hashtagify(t);
  return {
    groups: [
      {
        label: 'پرترافیک (دفع ریچ)',
        tags: ['#اینستاگرام', '#کسب_و_کار_اینترنتی', '#فروش_آنلاین', '#بازاریابی_محتوا', '#پیشنهاد_ویژه'],
      },
      {
        label: 'تخصصی (مخاطب هدف)',
        tags: [core, hashtagify(t.split(' ')[0]), '#محصول_باکیفیت', '#خرید_مطمئن', '#مشاوره_رایگان'],
      },
      {
        label: 'نیش و محلی (نرخ تبدیل بالا)',
        tags: [hashtagify(t + ' خاص'), '#فروش_ویژه', '#تخفیف_محدود', '#مشتری_راضی', '#ارسال_به_سراسر_کشور'],
      },
    ],
  };
}

