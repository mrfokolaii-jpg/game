const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const take = (arr, n) => [...arr].sort(() => Math.random() - 0.5).slice(0, n);

function hashtagify(text) {
  return '#' + String(text).replace(/[#\s_\-]+/g, '_').replace(/[^\u0600-\u06FF0-9_a-zA-Z]/g, '');
}

