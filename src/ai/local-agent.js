// ─── چت آزاد ایجنت ────────────────────────────────────────────
export function makeChat({ message }) {
  const m = String(message || '');
  if (/سلام|درود|hi|hello/i.test(m)) {
    return 'سلام! 👋 من دستیار هوشمند کنتاکتور اینستگرام هستم. می‌تونم براتون کپشن، ایده محتوا، هشتگ، اسکریپت ریلز و استوری بسازم، پاسخ دایرکت‌ها رو آماده کنم و بریف کمپین تبلیغاتی بنویسم. چه کمکی لازم دارید؟';
  }
  if (/محتوا|پست|کپشن/.test(m)) {
    return 'برای تولید محتوا به بخش «استودیو محتوا» برید؛ اونجا می‌تونید موضوع و لحن رو وارد کنید تا کپشن، هشتگ و ایده دریافت کنید. اگه موضوع همینجا بگید، می‌تونم راهنمایی‌تون کنم.';
  }
  return `سؤالتون دریافت شد: «${m}». برای بهترین نتیجه، درخواستتون رو با جزئیات (موضوع، لحن، هدف) بفرمایید؛ مثلاً: «برای معرفی تراریوم جدید یک کپشن فروش‌محور بنویس». 🎯`;
}
