// ─── پاسخ هوشمند دایرکت ───────────────────────────────────────
export function makeReply({ message = '', context = '' }) {
  const m = String(message);
  let intent = 'عمومی';
  let reply = '';

  if (/قیمت|هزینه|چنده|چقدر/.test(m)) {
    intent = 'استعلام قیمت';
    reply = 'سلام و وقت بخیر 🌿\nممنون از پیامتون. قیمت‌ها بسته به مدل و اندازه متفاوته؛ لطفاً مدلی که مدنظرتونه رو بفرمایید تا لیست قیمت به‌روز رو براتون ارسال کنم. در صورت خرید امروز، کد تخفیف ۲۰٪ هم براتون فعال می‌کنم. ✅';
  } else if (/ارسال|پیک|پست|تحویل|کجایی|شهر/.test(m)) {
    intent = 'ارسال و تحویل';
    reply = 'درود بر شما 🚚\nارسال به سراسر کشور داریم؛ برای تهران معمولاً ۱ تا ۲ روز کاری و برای شهرستان‌ها ۲ تا ۴ روز کاری طول می‌کشه. بسته‌بندی کاملاً استاندارد و ضربه‌گیر داره و سلامت کالا تضمین می‌شه. 👌';
  } else if (/موجود|انبار|دارید/.test(m)) {
    intent = 'موجودی';
    reply = 'سلام دوست عزیز ❤️\nبله، این مدل فعلاً موجوده. اگه دوست دارید همین الان براتون رزرو کنم، لطفاً نام و آدرس کامل رو دایرکت بفرمایید. موجودی محدوده و اولویت با سفارش‌های قطعیه.';
  } else if (/زرد|پوسید|آفت|بیماری|خراب|مشکل/.test(m)) {
    intent = 'پشتیبانی';
    reply = 'سلام، نگران نباشید 🙏\nلطفاً یک ویدیوی کوتاه از وضعیت گیاه/محصول بفرستید تا دقیق بررسی کنم. در بیشتر موارد با تنظیم آبیاری و نور مشکل حل می‌شه. راهنمای کامل مراقبت هم براتون ارسال می‌شه.';
  } else if (/تخفیف|آفر|حراج/.test(m)) {
    intent = 'تخفیف';
    reply = 'سلام وقت بخیر 🎁\nکد تخفیف ۲۰٪ ما با عنوان SABZ20 همین الان براتون فعال شد و تا ۴۸ ساعت اعتبار داره. کافیه هنگام سفارش دایرکت اعلام کنید تا در فاکتور لحاظ بشه.';
  } else {
    intent = 'آشنایی و اطلاعات';
    reply = `سلام و خوش آمدید 🌿\nممنون که به ما پیام دادید. من دستیار هوشمند صفحه هستم و می‌تونم درباره محصولات، قیمت، ارسال و مشاوره راهنمایی‌تون کنم. لطفاً سؤالتون رو دقیق بفرمایید تا در کمترین زمان پاسخ بدم. 💬`;
  }
  if (context) reply += `\n\n(با در نظر گرفتن زمینه: ${context})`;
  return { intent, reply };
}

